def describe(n: Niche) -> str:
    return (f"<b>{n.title}</b>\n{n.profile}\n\nФразы: {', '.join(n.phrases[:5])}…\n"
            f"Услуги: {', '.join(sorted(set(n.topic.values())))}\nРубрики: {', '.join(n.pillars)}")


async def apply(db, phrases, n: Niche) -> None:
    """Профиль, фразы, словарь тем (намерения и стоп-слова остаются общими) и рубрики контента."""
    await db.set_setting("profile", n.profile)
    await db.set_setting("niche", n.key)
    await db.set_setting("pillars", "; ".join(n.pillars))
    await phrases.set(n.phrases)
    await db.conn.execute("DELETE FROM keywords WHERE kind = 'topic'")
    await db.conn.executemany("INSERT OR REPLACE INTO keywords VALUES ('topic', ?, ?)", list(n.topic.items()))
    await db.conn.commit()
    if n.yandex_queries:
        await db.set_setting("yandex_queries", ", ".join(n.yandex_queries))
